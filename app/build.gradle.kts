// `./gradlew check` runs everything: compile (warnings are errors), lint, detekt with type
// resolution, unit + Robolectric tests, and the coverage gate.
val fetchWhisperModel by tasks.registering {
    description = "Downloads $WHISPER_MODEL for voice typing and checks its SHA-256."
    val out = layout.buildDirectory.file("generated/whisper/whisper/model.bin")
    inputs.property("sha256", WHISPER_SHA256)
    outputs.file(out)
    doLast {
        val file = out.get().asFile
        fun sha256(f: File) = MessageDigest.getInstance("SHA-256").let { md ->
            f.inputStream().use { input -> md.update(input.readBytes()) }
            md.digest().joinToString("") { "%02x".format(it) }
        }
        if (!file.exists() || sha256(file) != WHISPER_SHA256) {
            file.parentFile.mkdirs()
            URI(WHISPER_URL).toURL().openStream().use { input -> file.outputStream().use { input.copyTo(it) } }
            val got = sha256(file)
            if (got != WHISPER_SHA256) {
                file.delete()
                throw GradleException("$WHISPER_MODEL: SHA-256 $got, expected $WHISPER_SHA256")
            }
        }
    }
}
